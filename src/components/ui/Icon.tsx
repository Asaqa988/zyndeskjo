export function Icon({
  name,
  className,
  size = 24,
  strokeWidth = 1.75,
  'aria-hidden': ariaHidden = true,
}: {
  name: string;
  className?: string;
  size?: number;
  strokeWidth?: number;
  'aria-hidden'?: boolean;
}) {
  const Cmp = registry[name] ?? Boxes;
  return (
    <Cmp className={className} size={size} strokeWidth={strokeWidth} aria-hidden={ariaHidden} />
  );
}
